function V = report(D, opt)
%LSQVCE.REPORT  Judge a least-squares adjustment and say so in words.
%
%   V = LSQVCE.REPORT(D) takes the struct from lsqvce.engine.verdict.diagnose and prints a
%   verdict. It returns a struct of machine-readable findings so the same logic
%   can drive an automated pipeline.
%
%   The report is ordered so that a failure at one level invalidates the levels
%   below it. It refuses to report parameter precision for an adjustment whose
%   integrity checks failed, because a sigma computed from a broken system is
%   not a conservative estimate -- it is a fabrication.
%
%   LEVELS
%     0  INTEGRITY   sum(r) == n-u, vPv >= 0, vPv consistent between passes.
%                    These test the CODE, not the data. Failure here means
%                    every number below is meaningless.
%     1  GLOBAL      variance factor vs chi-square.
%     2  LOCALISE    outliers (data snooping), with Bonferroni.
%     3  RELIABILITY redundancy numbers, MDB, external reliability.
%                    This is the level that says which observations you are
%                    NOT ABLE TO CHECK.
%     4  PARAMETERS  correlations, conditioning, precision.
%
%   NAME-VALUE
%     'verbose'  true  print the report (default true)
%     'width'    78    line width
%     'Provenance' struct()  a run-provenance struct (LSQVCE.RESULTS .meta);
%                      when non-empty, ONE level-0 NOTE line
%                      (code 'PROVENANCE') states toolbox version, MATLAB
%                      release, and creation time. R.report() forwards it
%                      automatically; a bare lsqvce.report(D) prints none.
%     'Iteration'  struct()  the loop state of an ITERATIVE run:
%                      .converged, .stopReason, .nIter and optionally .what
%                      (the loop's name; default 'stochastic model'). When non-empty and the
%                      run was not a single solve, ONE level-1 line says
%                      whether the stochastic model settled -- 'NOISE_SETTLED'
%                      (NOTE) or 'NOISE_UNSETTLED' (WARN). Every number from
%                      level 1 down rests on those weights, so a model that was
%                      still moving qualifies all of them. R.report() forwards
%                      it automatically. An optional .influence (char) names
%                      the robust influence of an IRLS run; when non-empty ONE
%                      level-1 NOTE ('ROBUST_FIT') says sigma0 and the
%                      covariance are those of the reweighted problem.
%
%   OUTPUT V
%     V.verdict   'PASS' | 'PASS WITH WARNINGS' | 'SUSPECT' | 'INVALID'
%     V.findings  cell array of struct(level, severity, code, msg)
%     V.nError, V.nWarn, V.nNote
%
%   INPUT
%     D         1x1 struct  diagnostics from LSQVCE.ENGINE.VERDICT.DIAGNOSE
%     varargin  Name/Value: 'verbose', 'width', 'alpha', 'rWeak', ...
%
%   EXAMPLE
%       data = struct('batchFcn', src, 'numUnknowns', u, 'numBatches', 4);
%       R = lsqvce.fit(data, Verbose=false);
%       V = lsqvce.report(R.diag);         % prints the five levels (= R.report)
%
%       % V.verdict    'PASS' | 'PASS WITH WARNINGS' | 'SUSPECT' | 'INVALID'
%       % V.findings   machine-readable: {level, severity, code, msg}
%
%       % Drive a pipeline off the codes rather than the text:
%       codes = cellfun(@(f) f.code, V.findings, 'UniformOutput', false);
%       if ismember('SNOOP_CONTAMINATED', codes)
%           error('Pope is blind here -- re-run with test=mad.');
%       end
%
%   See also LSQVCE.ENGINE.VERDICT.DIAGNOSE, LSQVCE.ENGINE.VERDICT.SYSTEMATIC.
%
%   Updated 2026-10-12 (CEST, UTC+02:00), WP-125: the contamination cross-check
%   runs whatever the Bonferroni setting; the PASS text claims only what
%   REL_EXTERNAL measures; the remedies name Backend = "qr"; Iteration.what
%   names the loop that iterated. With assistance from Claude (Anthropic), model
%   Claude Opus 5.5.
%   Updated 2026-08-19 (CEST, UTC+02:00), WP-39 stage (b) b2 (F-07):
%   typed `arguments` signature, canonical UpperCamelCase option names
%   (legacy casings keep matching -- MATLAB NV semantics; enum VALUES
%   case-sensitive lowercase). With assistance from Claude (Anthropic),
%   model Claude Fable 5.
%
%   Updated 2026-10-11 (CEST, UTC+02:00), R7 WP-86 part 4: the remedies name
%   R.systematic() / R.snoop(), never an engine function (H-05). With
%   assistance from Claude (Anthropic), model Claude Opus 5.5.
%   Updated 2026-10-10 (CEST, UTC+02:00), R7 WP-86 part 2 (R7-24): PAR_COND
%   states how the lower bound on cond(N) is formed (from the block
%   cofactor, no SVD). With assistance from Claude (Anthropic), model Claude
%   Opus 5.5.
%   Updated 2026-10-10 (CEST, UTC+02:00), R7 WP-115 (finding R7-18):
%   adjustRobust's help promised "report() says so" and report said nothing --
%   a robust fit's sigma0 and covariance are those of the REWEIGHTED problem,
%   not an M-estimator's scale or sandwich covariance, and the level-1 test
%   and the bounds read them as least squares. Iteration.influence now puts
%   one NOTE in the verdict. With assistance from Claude (Anthropic), model
%   Claude Opus 5.5.
%   Updated 2026-09-08 (CEST, UTC+02:00), R6 WP-99: the new 'Iteration'
%   option puts ONE level-1 line in the verdict saying whether the stochastic
%   model settled -- a report that stays silent about weights that were still
%   moving is a report that misleads. With assistance from Claude (Anthropic),
%   model Claude Opus 5.
%   Generated with assistance from Claude (Anthropic), Claude Opus 4.8,
%   2026-07-11.
%   Updated 2026-10-12 (CEST, UTC+02:00), WP-124: development history taken
%   out of the help text (it lives in RELEASE_NOTES.md and dev/HANDOVER.md);
%   references point at the API reference. With assistance from Claude
%   (Anthropic), model Claude Opus 5.5.

% WP-39 b2: typed `arguments` signature (canonical Verbose/Width;
% legacy casings keep matching -- MATLAB NV semantics).
arguments
    D
    opt.Verbose (1,1) logical = true
    opt.Width (1,1) double {mustBeGreaterThanOrEqual(opt.Width, 40)} = 78
    opt.Provenance (1,1) struct = struct()   % WP-44: Results.meta, prints one
                                             % level-0 line when non-empty
    opt.Iteration (1,1) struct = struct()    % R6 WP-99: .converged .stopReason
                                             % .nIter of an iterative run; one
                                             % level-1 line when non-empty and
                                             % the run was not a single solve
end

verbose = opt.Verbose;
W = opt.Width;

F = {};   % findings
    function push(lvl, sev, code, fmt, varargin)
        F{end+1} = struct('level', lvl, 'severity', sev, 'code', code, ...
                          'msg', sprintf(fmt, varargin{:})); %#ok<AGROW>
    end

%% ===================================================== LEVEL 0: INTEGRITY
% These are checks on the arithmetic, not on the data. They come first because
% if the accumulator and the second pass disagree, no conclusion drawn from
% either is worth anything.

integrityOK = true;

% WP-44: the ONE provenance line, level 0 -- present in V.findings (code
% 'PROVENANCE') and printed with the level-0 block. Only when a provenance
% struct was forwarded (lsqvce.Results/report does; a bare lsqvce.report(D)
% prints none).
if ~isempty(fieldnames(opt.Provenance))
    P = opt.Provenance;
    push(0, 'NOTE', 'PROVENANCE', ...
        'run: lsqvce %s, MATLAB R%s, created %s', ...
        pf(P, 'toolboxVersion'), pf(P, 'matlabRelease'), pf(P, 'createdUTC'));
end

if D.sumRRelErr > 1e-6
    integrityOK = false;
    push(0, 'ERROR', 'SUM_R', ...
        ['sum(r_i) = %.6f but n - u = %d  (relative error %.2e).\n' ...
         'This identity is exact in theory. Its violation means the second ' ...
         'pass is NOT replaying the same design matrix the accumulator saw, ' ...
         'or the weights differ between passes. Every diagnostic below is ' ...
         'attributed to the wrong observation. Fix this before reading on.'], ...
         D.sumR, D.sumRExpect, D.sumRRelErr);
else
    push(0, 'NOTE', 'SUM_R', ...
        'sum(r_i) = %.6f vs n-u = %d  (rel. err %.1e)  [identity holds]', ...
         D.sumR, D.sumRExpect, D.sumRRelErr);
end

if ~isfinite(D.vPv) || D.vPv < 0
    integrityOK = false;
    push(0, 'ERROR', 'VPV_SIGN', ...
        ['vPv = %.6e is negative or non-finite. A weighted sum of squares ' ...
         'cannot be. This is a numerical failure, not a data problem.'], D.vPv);
end

% The two vPv estimates. A large disagreement is diagnostic in itself.
if isfinite(D.vPvAccum) && D.vPvAccum > 0 && D.vPvRelDiff > 1e-6
    sev = 'WARN';
    if D.vPvRelDiff > 1e-2, sev = 'ERROR'; integrityOK = false; end
    push(0, sev, 'VPV_MISMATCH', ...
        ['vPv from the accumulator (%s) = %.8e\n' ...
         'vPv recomputed from residuals   = %.8e   (rel. diff %.2e)\n' ...
         'The accumulator formed vPv as l''Pl - b''x, a difference of two ' ...
         'nearly equal large numbers. When the fit is tight this cancellation ' ...
         'destroys the result. The recomputed value is the trustworthy one and ' ...
         'is what this report uses. If you need the cheap path to be right, ' ...
         're-run with Backend = "qr" (lsqvce.Options).'], ...
         D.vPvSource, D.vPvAccum, D.vPv, D.vPvRelDiff);
end

if D.r == 0
    integrityOK = false;
    push(0, 'ERROR', 'NO_REDUNDANCY', ...
        ['Redundancy is ZERO (n = u = %d). The model reproduces the data ' ...
         'exactly by construction: all residuals are 0, sigma0 is undefined, ' ...
         'and no statistical test of any kind exists.\n' ...
         'This adjustment has been COMPUTED but it cannot be JUDGED. Nothing ' ...
         'below this line means anything.'], D.u);
end

if D.s0Fallback
    push(0, 'WARN', 'S0_FALLBACK', ...
        ['The estimated variance factor was unusable, so residuals were ' ...
         'studentised with the A PRIORI sigma0 = %.4g instead. Treat the ' ...
         'w statistics as Baarda-type, not Pope-type.'], D.sigma0);
end

%% ======================================================== LEVEL 1: GLOBAL
% R6 WP-99: FIRST, whether the weights this level judges had settled at all.
% Every number from here down rests on the stochastic model, so a model that
% was still moving when the loop stopped qualifies all of them. The engine
% warns (lsqvce:adjustVCEjoint:notConverged), but warnings are routinely muted
% -- this toolbox's own suite mutes that one in three places -- and a verdict
% that stays silent about it is a verdict that misleads. Nothing is said for a
% single solve, which has no loop: stopReason "single".
if isfield(opt.Iteration, 'influence') && ~isempty(opt.Iteration.influence)
    push(1, 'NOTE', 'ROBUST_FIT', ...
        ['This is a robust (%s) fit: sigma0 and the covariance are those of the ' ...
         'REWEIGHTED problem -- not an M-estimator''s scale nor its sandwich ' ...
         'covariance. The global test and the parameter bounds below read them as ' ...
         'least squares and are approximate in both directions.'], ...
         char(opt.Iteration.influence));
end
if ~isempty(fieldnames(opt.Iteration))
    it = opt.Iteration;  what = char(lsqvce.util.getfielddef(it, 'what', 'stochastic model'));
    if ~strcmp(char(it.stopReason), 'single')
        if it.converged
            push(1, 'NOTE', 'NOISE_SETTLED', ...
                'The %s settled in %d pass(es).', what, it.nIter);
        else
            push(1, 'WARN', 'NOISE_UNSETTLED', ...
                ['The %s did NOT settle: the loop stopped after %d ' ...
                 'pass(es), stopReason "%s". The weights every number below rests ' ...
                 'on were still moving, so read what follows as provisional. Raise ' ...
                 'MaxPasses or loosen Tolerance and run this report again; ' ...
                 'R.convergence() shows what was still changing.'], ...
                 what, it.nIter, char(it.stopReason));
        end
    end
end

if integrityOK
    r     = D.r;
    ratio = D.varRatio;

    lo = lsqvce.kernel.stat.chi2Inv(0.005, r) / r;
    hi = lsqvce.kernel.stat.chi2Inv(0.995, r) / r;

    T  = D.vPv / D.sigma0^2;
    inBand = (ratio >= lo) && (ratio <= hi);

    push(1, 'NOTE', 'GLOBAL_STAT', ...
        ['s0^2/sigma0^2 = %.6f     T = vPv/sigma0^2 = %.4e\n' ...
         'chi2 acceptance band (alpha=1%%, r=%d): [%.6f, %.6f]  width %.2e'], ...
         ratio, T, r, lo, hi, hi - lo);

    % A confidence interval on sigma0 itself. The ratio alone invites
    % over-reading: a value of 1.05 means nothing at r = 50 and is a red flag
    % at r = 1e6, and nothing in the bare number says which.
    %   (r * s0^2) / sigma0^2 ~ chi2(r)
    % so a two-sided 95% interval for sigma0 is
    %   s0 * sqrt(r / chi2inv(0.975, r))  ..  s0 * sqrt(r / chi2inv(0.025, r))
    if r > 0 && isfinite(D.s0) && D.s0 > 0
        ciLo = D.s0 * sqrt(r / lsqvce.kernel.stat.chi2Inv(0.975, r));
        ciHi = D.s0 * sqrt(r / lsqvce.kernel.stat.chi2Inv(0.025, r));
        push(1, 'NOTE', 'GLOBAL_CI', ...
            ['sigma0_hat = %.5f,  95%% CI [%.5f, %.5f]   (a priori sigma0 = ' ...
             '%.5f)\n' ...
             'Read the INTERVAL, not the point estimate: at this redundancy ' ...
             '(r = %d) a deviation smaller than about %.1f%% is not ' ...
             'distinguishable from sampling noise.'], ...
             D.s0, ciLo, ciHi, D.sigma0, r, 100 * (ciHi - ciLo) / (2 * D.s0));
    end

    if inBand
        push(1, 'NOTE', 'GLOBAL_PASS', ...
            'Global test PASSES: functional and stochastic model are consistent.');
    else
        % The band collapses like 1/sqrt(r). At geodetic n it is so tight that
        % any real model imperfection rejects. Say what the rejection MEANS
        % rather than pretending it is fatal.
        bandWidth = hi - lo;
        if bandWidth < 0.02
            push(1, 'NOTE', 'GLOBAL_SHARP', ...
                ['NOTE: with r = %d the acceptance band is only +/-%.2f%%. At ' ...
                 'this redundancy the chi-square test rejects on ANY model ' ...
                 'imperfection, however small and however harmless. Do not read ' ...
                 'the rejection itself as fatal -- read the RATIO.'], ...
                 r, 100 * bandWidth / 2);
        end

        if ratio > hi
            push(1, 'WARN', 'GLOBAL_HIGH', ...
                ['Variance factor is HIGH by a factor of %.3f.\n' ...
                 'The residuals are larger than the weights promised. Exactly ' ...
                 'three things cause this, and the global test cannot tell them ' ...
                 'apart:\n' ...
                 '  (a) outliers            -> check the Level-2 flags below;\n' ...
                 '  (b) unmodelled systematics -> plot w against time, elevation,\n' ...
                 '      azimuth, temperature, satellite ID. The chi2 test and\n' ...
                 '      data snooping are BOTH blind to a smooth bias;\n' ...
                 '  (c) over-optimistic weights -> if the residuals are clean and\n' ...
                 '      structureless, run variance-component estimation.\n' ...
                 'Do NOT simply rescale Qxx by s0^2 until you have ruled out (a) ' ...
                 'and (b). Rescaling launders a blunder into a plausible sigma.'], ...
                 ratio);
        else
            push(1, 'WARN', 'GLOBAL_LOW', ...
                ['Variance factor is LOW by a factor of %.3f.\n' ...
                 'The residuals are SMALLER than the weights predicted. Usually:\n' ...
                 '  (a) pessimistic weights -- sigma0 was set too large; or\n' ...
                 '  (b) OVER-PARAMETERISATION -- the model has enough freedom to\n' ...
                 '      absorb the noise. This is the dangerous one: it produces\n' ...
                 '      a beautiful fit and meaningless parameters.\n' ...
                 'Check whether every parameter is actually justified (F-test on\n' ...
                 'the nested model), and look at the parameter correlations at\n' ...
                 'Level 4.'], ratio);
        end
    end
end

%% ====================================================== LEVEL 2: LOCALISE
if integrityOK
    % ---- CONTAMINATION CROSS-CHECK ------------------------------------
    % Pope's tau studentises by s0, s0 is estimated from data that CONTAIN the
    % blunders, and so a group of blunders inflates the denominator and hides
    % itself. At 10% contamination even a 100-sigma blunder is undetectable and
    % the snooping result reads "clean".
    %
    % But the robust cure has a cliff of its own, so we escalate on the
    % contamination FRACTION, not on a scale ratio -- see diagnose() for the
    % measured curves.
    if isfield(D, 'contamLevel')
        switch D.contamLevel

        case 'breakdown'
            % The most dangerous state. fhat says ~0, so every scale-based
            % alarm has gone quiet -- but the a-priori backstop says the
            % residuals are enormous. The robust scale has been CAPTURED by the
            % blunders and is now calling the good data outliers.
            push(2, 'ERROR', 'SNOOP_BREAKDOWN', ...
                ['TOTAL BREAKDOWN OF THE OUTLIER MACHINERY.\n' ...
                 'The robust scale reports almost no outliers (fhat = %.3f) ' ...
                 'while the a-priori backstop says the residuals are %.1fx ' ...
                 'larger than sigma0 promised.\n' ...
                 'These two statements are only compatible if MORE THAN HALF ' ...
                 'the data are bad: past ~40%% contamination the robust scale ' ...
                 'adopts the BLUNDERS as its reference population, and the good ' ...
                 'observations become "the outliers". Every scale-based ' ...
                 'indicator -- s0/MAD, kurtosis, fhat -- switches itself off at ' ...
                 'exactly this point. Measured: s0/MAD falls to 0.95 at 50%% ' ...
                 'contamination, BELOW its clean-data value of 1.02.\n' ...
                 'DO NOT REJECT ANYTHING. Do not trust any flag list on this ' ...
                 'page. Either sigma0 is badly wrong, or the functional model ' ...
                 'is. Fix the model first.'], ...
                 D.fhat, D.backstop);

        case 'refuse'
            push(2, 'ERROR', 'SNOOP_REFUSE', ...
                ['REFUSING TO TREAT THIS AS AN OUTLIER PROBLEM. An estimated ' ...
                 '%.0f%% of the observations (fhat = %.3f) are inconsistent ' ...
                 'with the rest.\n' ...
                 'If a quarter of your data are "outliers", they are not ' ...
                 'outliers. Rejecting them does not clean the data -- it ' ...
                 'launders a MODEL error into a plausible-looking result, and ' ...
                 'the surviving parameters will be confidently wrong.\n' ...
                 'The robust test is also degrading here (detection falls to ' ...
                 '~75%% at 30%% contamination and ~17%% at 40%%), so even the ' ...
                 'flag list you are looking at is incomplete.\n' ...
                 'Run R.systematic() and fix the functional model before ' ...
                 'rejecting a single observation.'], ...
                 100 * D.fhat, D.fhat);

        case 'severe'
            push(2, 'ERROR', 'SNOOP_CONTAMINATED', ...
                ['CONTAMINATION: an estimated %.0f%% of observations are bad ' ...
                 '(fhat = %.3f). s0 = %.4f against a robust scale of %.4f.\n' ...
                 'At this level Pope''s tau is BLIND: the blunders inflate s0, ' ...
                 'tau divides by s0, and they hide one another. Measured, a ' ...
                 '100-sigma blunder goes undetected at 10%% contamination.\n' ...
                 'Iterating does NOT rescue this -- if nothing trips the ' ...
                 'threshold on the first pass, the rejection loop exits at once ' ...
                 'having rejected nothing and reports "converged".\n' ...
                 'Use ''test'',''mad'' (robust scale, still ~100%% effective ' ...
                 'here) or Robust="huber" on fit. An empty flag list from a Pope run ' ...
                 'is NOT evidence of clean data.'], ...
                 100 * D.fhat, D.fhat, D.s0, D.robustScale);

        case 'moderate'
            push(2, 'WARN', 'SNOOP_MODERATE', ...
                ['An estimated %.0f%% of observations are outlying (fhat = ' ...
                 '%.3f). s0 = %.4f, robust scale = %.4f.\n' ...
                 'This is enough to start degrading Pope''s tau (detection ' ...
                 'falls to ~23%% at 5%% contamination). Prefer ''test'',''mad'' ' ...
                 'and reject iteratively rather than all at once.'], ...
                 100 * D.fhat, D.fhat, D.s0, D.robustScale);

        case 'clean'
            if ~strcmp(D.test, 'mad')
                push(2, 'NOTE', 'SNOOP_SCALECHECK', ...
                    ['Scale cross-check: s0 = %.4f, robust scale = %.4f ' ...
                     '(ratio %.3f), estimated contamination %.1f%%. They agree, ' ...
                     'so s0 is not being inflated by bad data and the flag list ' ...
                     'below can be believed.'], ...
                     D.s0, D.robustScale, D.scaleRatio, 100 * D.fhat);
            end

        otherwise   % 'unknown' -- correlated batches, too few residuals
            push(2, 'NOTE', 'SNOOP_NOCHECK', ...
                ['No robust scale could be formed (correlated batches, or too ' ...
                 'few usable residuals), so the contamination cross-check is ' ...
                 'unavailable. Pope''s tau is used unchecked -- be aware it goes ' ...
                 'blind above ~5%% contamination.']);
        end

        % The backstop is reported whenever it disagrees with sigma0, because
        % it is the ONE indicator contamination cannot switch off.
        if isfinite(D.backstop) && D.backstop > D.backstopTol ...
                && ~strcmp(D.contamLevel, 'breakdown')
            push(2, 'NOTE', 'SNOOP_BACKSTOP', ...
                ['A-priori backstop: s0/sigma0 = %.2f (clean-data tolerance ' ...
                 '%.2f). This indicator is monotone in the contamination and ' ...
                 'cannot be suppressed by it -- but it is only as good as your ' ...
                 'sigma0. If sigma0 is trustworthy, the residuals really are ' ...
                 '%.1fx larger than promised.'], ...
                 D.backstop, D.backstopTol, D.backstop);
        end
    end

    if strcmp(D.test, 'mad')
        push(2, 'NOTE', 'SNOOP_MAD', ...
            ['Using the ROBUST (MAD) scale = %.4f in place of s0 = %.4f. This ' ...
             'has a high breakdown point: it stays reliable to roughly 25%% ' ...
             'contamination, where Pope''s tau is already blind at 5-10%%. It ' ...
             'costs some efficiency on clean data (a noisier scale) but no ' ...
             'measurable increase in false alarms (0 in 300 clean runs).'], ...
             D.robustScale, D.s0);
    end

    if D.bonferroni
        push(2, 'NOTE', 'SNOOP_SETUP', ...
            ['Data snooping: %s test, alpha = %.1e per test, Bonferroni-' ...
             'corrected to %.2e for n = %d simultaneous tests.\n' ...
             'Critical value |w| > %.4f.   Expected false alarms: %.2f'], ...
             upper(D.test), D.alpha, D.alphaEff, D.n, D.kCrit, D.nExpectedFalse);
    else
        push(2, 'WARN', 'SNOOP_NOBONF', ...
            ['Data snooping with an UNCORRECTED alpha = %.1e over n = %d tests.\n' ...
             'You should expect about %.0f good observations to be flagged by ' ...
             'chance alone. That is not an outlier list, it is a noise list. ' ...
             'Set ''bonferroni'',true.'], D.alpha, D.n, D.nExpectedFalse);
    end

    if D.snoopVacuous
        push(2, 'ERROR', 'SNOOP_VACUOUS', ...
            ['The critical value (%.4f) EXCEEDS the upper bound of Pope''s tau ' ...
             '(sqrt(r) = %.4f). No residual can possibly exceed it, so data ' ...
             'snooping here is vacuous -- an empty outlier list is guaranteed ' ...
             'regardless of the data.\n' ...
             'The redundancy (%d) is simply too small to test %d observations ' ...
             'at this significance. Either accept a weaker alpha, or accept ' ...
             'that this network cannot detect its own blunders.'], ...
             D.kCrit, D.tauBound, D.r, D.n);
    elseif D.nFlag == 0
        push(2, 'NOTE', 'SNOOP_CLEAN', ...
            ['No observation exceeds the critical value. Largest |w| = %.4f ' ...
             '(observation %d), against a threshold of %.4f.'], ...
             D.maxAbsW, D.maxAbsWIdx, D.kCrit);
    else
        excess = D.nFlag - D.nExpectedFalse;
        push(2, 'WARN', 'SNOOP_FLAGS', ...
            ['%d observation(s) flagged  (expected by chance: %.2f, so about ' ...
             '%.1f are real).\n' ...
             'Largest |w| = %.4f at observation %d.'], ...
             D.nFlag, D.nExpectedFalse, max(excess, 0), D.maxAbsW, D.maxAbsWIdx);

        % Show the worst offenders WITH their redundancy numbers. A large w on
        % a low-r observation means something quite different from a large w on
        % a well-controlled one, and the pair must be read together.
        nShow = min(15, D.nFlag);
        [~, ord] = sort(abs(D.flagW), 'descend');
        tbl = sprintf('\n    %8s %12s %10s %8s %12s\n', ...
                      'obs', 'w', 'r_i', 'v', 'MDB');
        tbl = [tbl sprintf('    %s\n', repmat('-', 1, 54))];
        for jj = 1:nShow
            q = ord(jj);
            tbl = [tbl sprintf('    %8d %12.4f %10.4f %8.3g %12.4g\n', ...
                   D.flagIdx(q), D.flagW(q), D.flagR(q), D.flagV(q), ...
                   D.flagMDB(q))]; %#ok<AGROW>
        end
        if D.nFlag > nShow
            tbl = [tbl sprintf('    ... and %d more\n', D.nFlag - nShow)];
        end
        push(2, 'NOTE', 'SNOOP_TABLE', '%s', tbl);

        lowR = D.flagR < D.rWeak;
        if any(lowR)
            push(2, 'WARN', 'SNOOP_LOWR', ...
                ['%d of the flagged observations have r_i < %.2f. A large ' ...
                 'residual on a LOW-redundancy observation is ambiguous: the ' ...
                 'network barely constrains it, so the residual is as likely to ' ...
                 'be absorbed error from its neighbours as it is to be a blunder ' ...
                 'in that observation itself.\n' ...
                 'Rejecting these is a coin flip. Prefer to re-measure them.'], ...
                 sum(lowR), D.rWeak);
        end

        push(2, 'NOTE', 'SNOOP_ITER', ...
            ['Reject ONE observation at a time (the largest |w|), re-solve, and ' ...
             're-snoop -- R.snoop() does this for you.\n' ...
             'The reason is MASKING, not over-rejection: several blunders ' ...
             'inflate s0 together and therefore hide one another, so a single ' ...
             'pass MISSES some of them. Measured: with two equal blunders in a ' ...
             'small network, iterating found 100%% of them and a single pass ' ...
             'found 95%%; in wider sweeps the single pass missed dozens that ' ...
             'iterating caught. False positives were ~0 either way, so the ' ...
             'usual "simultaneous rejection throws away good data" argument is ' ...
             'not the point -- the point is that it leaves blunders IN.\n' ...
             'CAVEAT: iterating cannot rescue you if contamination is so heavy ' ...
             'that NOTHING trips the threshold on the first pass. The loop then ' ...
             'exits at once having rejected nothing, and reports "converged, 0 ' ...
             'rejections" -- which reads as clean. That is precisely what the ' ...
             'scale cross-check above exists to catch.']);
    end
end

%% =================================================== LEVEL 3: RELIABILITY
% The level people skip, and the level that actually determines whether the
% result can be trusted.
if integrityOK
    push(3, 'NOTE', 'REL_HEAD', ...
        ['Redundancy numbers: min = %.4e (observation %d), mean = %.4f\n' ...
         'MDB non-centrality delta0 = %.4f  (alpha_eff = %.2e, beta = %.2f)'], ...
         D.rMinSeen, D.rMinIdx, D.r / D.n, D.delta0, D.alphaEff, D.beta);

    % ---- THE JOINT (w, r) PICTURE -------------------------------------
    % A residual reveals only the FRACTION r_i of any error present:
    %     E[dv_i] = -r_i * b_i     (exact)
    % so |w| and r_i are meaningless in isolation. Measured on a levelling net
    % with a dangling spur: a 40-sigma blunder on an r = 0 observation gave
    % |w| = 0.000 -- a beautiful small residual on a grossly wrong observation.
    if isfield(D, 'quad')
        Q = D.quad;
        tbl = sprintf('\n    %-16s %8s   %s\n', 'quadrant', 'count', 'meaning');
        tbl = [tbl sprintf('    %s\n', repmat('-', 1, 68))];
        tbl = [tbl sprintf('    %-16s %8d   %s\n', 'clean outlier', ...
               Q.cleanOutlier, '|w| high, r high -> reject with confidence')];
        tbl = [tbl sprintf('    %-16s %8d   %s\n', 'AMBIGUOUS', ...
               Q.ambiguous,    '|w| high, r LOW  -> coin flip; re-measure')];
        tbl = [tbl sprintf('    %-16s %8d   %s\n', 'verified', ...
               Q.verified,     '|w| low,  r high -> tested, and passed')];
        tbl = [tbl sprintf('    %-16s %8d   %s\n', 'UNTESTED', ...
               Q.untested,     '|w| low,  r LOW  -> NOT "fine". No power.')];
        push(3, 'NOTE', 'REL_QUADRANTS', '%s', tbl);

        if Q.untested > 0
            push(3, 'WARN', 'REL_SILENT', ...
                ['%d observation(s) fall in the SILENT quadrant: their residual ' ...
                 'is small, but only because the network cannot see them. They ' ...
                 'did not PASS the test -- the test was never able to run.\n' ...
                 'A residual reports only the fraction r_i of any error present, ' ...
                 'so at r_i -> 0 an arbitrarily large blunder produces an ' ...
                 'arbitrarily small |w|. Nothing in the flag list above ' ...
                 'distinguishes these from genuinely healthy observations.'], ...
                 Q.untested);
        end

        if Q.ambiguous > 0
            push(3, 'WARN', 'REL_AMBIGUOUS', ...
                ['%d flagged observation(s) have LOW redundancy. A large ' ...
                 'residual on a weakly-controlled observation is ambiguous: the ' ...
                 'network barely constrains it, so the residual is as likely to ' ...
                 'be error absorbed from a NEIGHBOUR as a blunder in the ' ...
                 'observation itself. Rejecting these is close to a coin flip. ' ...
                 'Prefer to re-measure them.'], Q.ambiguous);
        end
    end

    % ---- THE HIDDEN-BLUNDER ENVELOPE ----------------------------------
    if isfield(D, 'mdbQuantiles') && isfinite(D.mdbQuantiles.p50)
        M = D.mdbQuantiles;
        push(3, 'NOTE', 'REL_ENVELOPE', ...
            ['Hidden-blunder envelope -- the largest error that could be ' ...
             'present in an observation WITHOUT tripping the test:\n' ...
             '    median %.2f   90th pct %.2f   99th pct %.2f   worst %.2f  ' ...
             '(in units of that observation''s own sigma)\n' ...
             'Read the median as: "half of my observations could harbour an ' ...
             'undetected error larger than %.1f sigma". That is a more honest ' ...
             'statement than any single worst-case number.'], ...
             M.p50, M.p90, M.p99, M.max, M.p50);
    end
    if isfield(D, 'mdbInf') && D.mdbInf > 0
        push(3, 'ERROR', 'REL_MDBINF', ...
            ['%d observation(s) have an INFINITE minimal detectable bias: no ' ...
             'error in them, however large, can ever be detected.\n' ...
             'Note these drop OUT of the percentiles above, so a finite-only ' ...
             'summary of the envelope looks reassuring precisely when it should ' ...
             'not. The infinities are the finding.'], D.mdbInf);
    end

    if D.nUncontrolled > 0
        % idxUncontrolled is capped during the sweep (we do not keep an
        % n-sized list), so it may hold fewer entries than nUncontrolled.
        idxU = D.idxUncontrolled(:).';
        nShowU = min(12, numel(idxU));
        if nShowU > 0
            idxStr = mat2str(idxU(1:nShowU));
        else
            idxStr = '(indices not retained)';
        end
        if numel(idxU) > nShowU || D.nUncontrolled > numel(idxU)
            more = ' ...';
        else
            more = '';
        end

        push(3, 'ERROR', 'REL_UNCONTROLLED', ...
            ['%d observation(s) have r_i ~ 0: they are COMPLETELY UNCONTROLLED.\n' ...
             'Their residual is forced to zero no matter what they contain. A ' ...
             'gross blunder in any of them passes into the parameters INTACT and ' ...
             'INVISIBLE -- it produces no residual, trips no test, and appears ' ...
             'nowhere in this report except here.\n' ...
             'A clean data-snooping result does not exonerate them. It cannot ' ...
             'even see them.\n' ...
             'First indices: %s%s'], ...
             D.nUncontrolled, idxStr, more);
    end

    if D.nWeak > 0
        push(3, 'WARN', 'REL_WEAK', ...
            ['%d observation(s) (%.1f%%) have r_i < %.2f: weakly controlled.\n' ...
             'A blunder in these is only partly visible in the residuals; most ' ...
             'of it goes into the parameters. Data snooping has low power here.'], ...
             D.nWeak, 100 * D.nWeak / D.n, D.rWeak);
    end

    if D.nUncontrolled == 0 && D.nWeak == 0
        push(3, 'NOTE', 'REL_GOOD', ...
            ['Every observation has r_i >= %.2f: the network controls all of ' ...
             'its observations and data snooping has power everywhere.'], D.rWeak);
    end

    % External reliability -- the number that actually matters.
    %
    % CALIBRATION. extMax is NOT a scale-free quantity. Measured on CLEAN,
    % healthy data it behaves like
    %
    %       extMax  ~  4.0 * delta0 / sqrt(n)
    %
    % Medians over 40 realisations (u = 6, unit weights):
    %
    %       n        100    300    500   1000   2000   5000  10000
    %       extMax  1.827  1.126  0.900  0.698  0.514  0.365  0.265
    %       ratio    3.48   3.55   3.60   3.85   3.92   4.27   4.29
    %
    % A FIXED threshold of 1.0 is therefore scientifically meaningless: it fires
    % on 100% of clean datasets with n <= 500 and essentially never for
    % n >= 2000, REGARDLESS OF THE ACTUAL QUALITY of the network.
    %
    % It shipped that way as an ERROR, and was caught only when the suite was
    % finally run in MATLAB: a perfectly clean n = 500 adjustment was being
    % reported as SUSPECT. The honest question is not "is extMax > 1?" but
    % "is extMax worse than a healthy network OF THIS SIZE would give?".
    if isfinite(D.extMax) && D.extMax > 0
        if isfield(D, 'extExpect')
            extExpect = D.extExpect;
        else
            extExpect = 4.0 * D.delta0 / sqrt(max(D.n, 1));
        end
        extRatio = D.extMax / max(extExpect, realmin);

        if extRatio > 3.0
            sev = 'ERROR';
            verdictMsg = sprintf( ...
                ['This is %.1fx WORSE than a healthy network of this size ' ...
                 '(n = %d) would give (expected ~%.2f sigma). The geometry is ' ...
                 'badly weak: one observation carries far more leverage than ' ...
                 'the rest. Find it -- look at min r_i -- rather than trusting ' ...
                 'the formal sigmas.'], extRatio, D.n, extExpect);
        elseif extRatio > 1.8
            sev = 'WARN';
            verdictMsg = sprintf( ...
                ['This is %.1fx what a healthy network of this size (n = %d) ' ...
                 'would give (expected ~%.2f sigma). The geometry is weaker ' ...
                 'than it should be.'], extRatio, D.n, extExpect);
        else
            sev = 'NOTE';
            verdictMsg = sprintf( ...
                ['That is normal for a network of this size (n = %d, expected ' ...
                 '~%.2f sigma). External reliability scales like 1/sqrt(n), so ' ...
                 'this is a property of how much data you have, not a defect.'], ...
                 D.n, extExpect);
        end

        % The ABSOLUTE statement, which is what the user must actually act on.
        if D.extMax > 1.0
            verdictMsg = [verdictMsg sprintf([ ...
                '\nIn ABSOLUTE terms it still exceeds one sigma, so an ' ...
                'undetectable blunder could move that parameter by more than ' ...
                'its stated precision. At n = %d that is EXPECTED, and the ' ...
                'cure is MORE OBSERVATIONS, not a better estimator.'], D.n)];
        end
        push(3, sev, 'REL_EXTERNAL', ...
            ['External reliability: the worst undetectable bias (the MDB of ' ...
             'observation %d) would shift parameter %d by %.3f of its own ' ...
             'sigma.\n%s'], D.extMaxIdx, D.extMaxPar, D.extMax, verdictMsg);
    end
end

%% ==================================================== LEVEL 4: PARAMETERS
if integrityOK
    % Every fit's diagnostics give cond(N) as a LOWER BOUND (WP-86 part 2):
    % the largest diagonal entries and Rayleigh quotients of N and of its
    % inverse, from the block cofactor -- an SVD of the u_full x u_full
    % factor is exactly the O(u^3) step the block-native diagnostics remove.
    %
    % A lower bound can only UNDER-report trouble, never invent it -- but it
    % must not be printed as though it were exact, or a run looks better
    % conditioned than it is.
    if isfield(D, 'condIsBound') && D.condIsBound
        push(4, 'NOTE', 'PAR_COND', ...
            ['cond(R) >= %.3e     cond(N) >= %.3e   [LOWER BOUND]\n' ...
             'The condition number is bounded from the cofactor''s blocks (the ' ...
             'largest diagonal entries and power iterations on N and its ' ...
             'inverse) rather than by an SVD of the full factor. This is a ' ...
             'lower bound: the true conditioning may be WORSE than shown, never ' ...
             'better. The ill-conditioning thresholds below are optimistic.'], D.condR, D.condN);
    else
        push(4, 'NOTE', 'PAR_COND', ...
            'cond(R) = %.3e     cond(N) = %.3e   [exact, from SVD]', ...
            D.condR, D.condN);
    end

    if D.condN > 1e14
        push(4, 'ERROR', 'PAR_ILLCOND', ...
            ['cond(N) = %.2e. In double precision this leaves essentially no ' ...
             'correct digits in the parameters. The standard deviations printed ' ...
             'below are FICTION.\n' ...
             'Rescale the parameters so their columns have comparable norm, ' ...
             'and/or run with Backend = "qr" (lsqvce.Options), which avoids squaring ' ...
             'the condition number.'], D.condN);
    elseif D.condN > 1e10
        push(4, 'WARN', 'PAR_ILLCOND', ...
            ['cond(N) = %.2e: roughly %.0f of the 16 significant digits are ' ...
             'gone. Parameter sigmas are optimistic. Consider rescaling the ' ...
             'columns of A, or the QR path.'], D.condN, log10(D.condN));
    end

    if D.corrMax > 0.999
        push(4, 'ERROR', 'PAR_CORR', ...
            ['Parameters %d and %d are correlated at %.5f. They are NOT ' ...
             'separately determined by these observations -- only some linear ' ...
             'combination of them is.\n' ...
             'Their individual standard deviations are meaningless in isolation, ' ...
             'however small they look. Either fix one parameter, reparameterise ' ...
             'to estimate the well-determined combination directly, or add ' ...
             'observations that separate them.'], ...
             D.corrMaxPar(1), D.corrMaxPar(2), D.corrMax);
    elseif D.corrMax > 0.95
        push(4, 'WARN', 'PAR_CORR', ...
            ['Maximum parameter correlation is %.4f (parameters %d and %d). ' ...
             'These are nearly inseparable; treat their individual sigmas with ' ...
             'suspicion and look at the error ellipse instead.'], ...
             D.corrMax, D.corrMaxPar(1), D.corrMaxPar(2));
    else
        push(4, 'NOTE', 'PAR_CORR', ...
            'Maximum parameter correlation is %.4f (parameters %d and %d).', ...
            D.corrMax, D.corrMaxPar(1), D.corrMaxPar(2));
    end

    % Parameter table, formal sigma and the s0-scaled sigma side by side.
    scale = D.s0;
    tbl = sprintf('\n    %5s %16s %14s %14s\n', ...
                  'par', 'x', 'sigma(a priori)', 'sigma(scaled)');
    tbl = [tbl sprintf('    %s\n', repmat('-', 1, 53))];
    for j = 1:min(D.u, 30)
        tbl = [tbl sprintf('    %5d %16.8g %14.6g %14.6g\n', ...
               j, D.x(j), D.sigma0 * D.sigX(j), scale * D.sigX(j))]; %#ok<AGROW>
    end
    if D.u > 30
        tbl = [tbl sprintf('    ... %d more parameters\n', D.u - 30)];
    end
    push(4, 'NOTE', 'PAR_TABLE', '%s', tbl);

    if abs(D.varRatio - 1) > 0.1
        push(4, 'WARN', 'PAR_SCALE', ...
            ['The two sigma columns differ by a factor of %.3f. Which one is ' ...
             'honest depends ENTIRELY on why the variance factor deviates:\n' ...
             '  - if the weights were wrong  -> the SCALED column is right;\n' ...
             '  - if there are outliers or systematics -> NEITHER is right, and\n' ...
             '    scaling merely dresses a broken model in a plausible sigma.\n' ...
             'Resolve Level 1 and Level 2 before quoting either.'], D.s0 / D.sigma0);
    end
end

%% ================================================================ VERDICT
sev = cellfun(@(f) f.severity, F, 'UniformOutput', false);
nErr  = sum(strcmp(sev, 'ERROR'));
nWarn = sum(strcmp(sev, 'WARN'));
nNote = sum(strcmp(sev, 'NOTE'));

if ~integrityOK
    verdict = 'INVALID';
    vmsg = ['The integrity checks failed. This is a defect in the setup or the ' ...
            'arithmetic, not a judgement about the data. Nothing in this report ' ...
            'can be relied on until it is fixed.'];
elseif nErr > 0
    verdict = 'SUSPECT';
    vmsg = ['The adjustment computed, but at least one finding is serious enough ' ...
            'that the result should not be published as it stands. See the ERROR ' ...
            'items.'];
elseif nWarn > 0
    verdict = 'PASS WITH WARNINGS';
    vmsg = ['No disqualifying finding, but there are issues that a competent ' ...
            'reviewer will ask about. Address the WARN items or be ready to ' ...
            'defend them.'];
else
    verdict = 'PASS';
    vmsg = ['All checks passed: the model is consistent, no outliers, every observation ' ...
            'is controlled, and the worst undetectable blunder moves a parameter no more ' ...
            'than this geometry leads one to expect (its size: the REL_EXTERNAL line).'];
end

V = struct('verdict', verdict, 'message', vmsg, 'findings', {F}, ...
           'nError', nErr, 'nWarn', nWarn, 'nNote', nNote, ...
           'integrityOK', integrityOK);

%% ================================================================= PRINT
if ~verbose, return; end

names = {'INTEGRITY  (does the arithmetic hold?)', ...
         'GLOBAL     (is the model consistent?)', ...
         'LOCALISE   (where is it broken?)', ...
         'RELIABILITY(what can you not check?)', ...
         'PARAMETERS (what do you actually know?)'};

lsqvce.util.log.msg('\n%s\n', repmat('=', 1, W));
lsqvce.util.log.msg('  LEAST-SQUARES ADJUSTMENT REPORT\n');
lsqvce.util.log.msg('  n = %d observations,  u = %d parameters,  r = n-u = %d\n', ...
        D.n, D.u, D.r);
lsqvce.util.log.msg('  %d batches,  vPv source: %s\n', D.nBatch, D.vPvSource);
lsqvce.util.log.msg('%s\n', repmat('=', 1, W));

for lv = 0:4
    sel = cellfun(@(f) f.level == lv, F);
    if ~any(sel), continue; end
    lsqvce.util.log.msg('\n--- LEVEL %d: %s\n', lv, names{lv+1});
    idx = find(sel);
    for q = idx(:).'
        f = F{q};
        switch f.severity
            case 'ERROR', tag = '[ERROR]';
            case 'WARN',  tag = '[WARN ]';
            otherwise,    tag = '       ';
        end
        printWrapped(tag, f.msg, W);
    end
end

lsqvce.util.log.msg('\n%s\n', repmat('=', 1, W));
lsqvce.util.log.msg('  VERDICT: %s        (%d error, %d warning, %d note)\n', ...
        verdict, nErr, nWarn, nNote);
printWrapped('  ', vmsg, W);
lsqvce.util.log.msg('%s\n\n', repmat('=', 1, W));

end

%% ----------------------------------------------------------------- helpers
function printWrapped(tag, msg, W)
%PRINTWRAPPED  Word-wrap a message to width W under a hanging label, via the log.
%   Emits msg through lsqvce.util.log.msg, wrapping prose lines so the tag prints
%   once on the first line and subsequent lines are indented to align under it.
%   Blank lines are preserved; pre-formatted table lines (starting with 4 spaces)
%   are passed through unwrapped.
%   INPUT
%     tag  1xk char    the leading label printed on the first wrapped line
%     msg  1xn char    the message (may contain '\n' separators and table blocks)
%     W    1x1 double  the target wrap width in characters
%   OUTPUT  none (writes via lsqvce.util.log.msg)
    lines = strsplit(msg, '\n');
    first = true;
    for i = 1:numel(lines)
        ln = lines{i};
        if isempty(strtrim(ln)) && ~first
            lsqvce.util.log.msg('\n'); continue;
        end
        % Pre-formatted blocks (tables) start with 4 spaces: do not re-wrap.
        if startsWith(ln, '    ')
            lsqvce.util.log.msg('%s\n', ln);
            first = false;
            continue;
        end
        words = strsplit(strtrim(ln), ' ');
        cur = '';
        for j = 1:numel(words)
            cand = strtrim([cur ' ' words{j}]);
            if numel(cand) + 9 > W && ~isempty(cur)
                emit(tag, cur, first); first = false;
                cur = words{j};
            else
                cur = cand;
            end
        end
        if ~isempty(cur)
            emit(tag, cur, first); first = false;
        end
    end
end

function emit(tag, txt, first)
%EMIT  Print one wrapped line: the tag on the first line, blanks aligned after.
%   INPUT
%     tag    1xk char    the label
%     txt    1xm char    the line content
%     first  1x1 logical true on the first line (prints tag); else indents
%   OUTPUT  none (writes via lsqvce.util.log.msg)
    if first
        lsqvce.util.log.msg('%s%s\n', tag, txt);
    else
        lsqvce.util.log.msg('%s%s\n', repmat(' ', 1, numel(tag)), txt);
    end
end



function v = pf(P, name)
%PF  Read a provenance field defensively for the level-0 line (WP-44).
%   INPUT
%     P     1x1 struct  the forwarded provenance struct
%     name  1xk char    field name
%   OUTPUT
%     v     1xm char    the field as char, or '?' when absent/non-char --
%                       a malformed provenance must never break the report
    if isfield(P, name) && (ischar(P.(name)) || (isstring(P.(name)) && isscalar(P.(name))))
        v = char(P.(name));
    else
        v = '?';
    end
end
